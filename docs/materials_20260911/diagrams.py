def flow(title, nodes, note, *, warning=False):
    assert len(nodes) == 6
    positions = [(20, 25), (427, 25), (834, 25),
                 (834, 258), (427, 258), (20, 258)]
    return dict(title=title, note=note, width=WIDTH, height=HEIGHT,
                nodes=[dict(x=x, y=y, w=346, h=164, title=name,
                            body=body, tone=("amber" if warning and i == 5 else
                                             "teal" if i in (0, 5) else "blue"),
                            step=f"{i + 1:02d}")
                       for i, ((x, y), (name, body)) in enumerate(zip(positions, nodes))],
                edges=[(i, i + 1) for i in range(5)])


def lanes(title, rows, note):
    return dict(title=title, note=note, width=WIDTH, height=HEIGHT,
                nodes=[dict(x=20, y=15 + i * 108, w=1160, h=86,
                            title=title, body=body, tone="teal" if i % 2 == 0 else "blue",
                            step="", lane=True)
                       for i, (title, body) in enumerate(rows)],
                edges=[(i, i + 1) for i in range(len(rows) - 1)])


