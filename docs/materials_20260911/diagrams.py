def edge_points(a, b):
    if a["y"] == b["y"]:
        direction = 1 if b["x"] > a["x"] else -1
        return ((a["x"] + (a["w"] if direction > 0 else 0), a["y"] + a["h"] / 2),
                (b["x"] + (0 if direction > 0 else b["w"]), b["y"] + b["h"] / 2))
    return ((a["x"] + a["w"] / 2, a["y"] + a["h"]),
            (b["x"] + b["w"] / 2, b["y"]))
